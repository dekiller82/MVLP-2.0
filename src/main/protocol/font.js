/** Width of `text` in glyph units (3 columns per glyph plus a 1 column gap). */
function textUnits(text) {
  return text.length * 3 + (text.length - 1);
}

/** Largest integer scale (<= maxScale) at which `text` fits in `width` with a pixel to spare each side. */
function fitScale(text, width, maxScale) {
  return Math.max(1, Math.min(maxScale, Math.floor((width - 2) / textUnits(text))));
}

